import express from 'express';
import * as validation from './predefinedCustomDescription.validation';
import { PredefinedCustomDescriptionController} from './predefinedCustomDescription.controller';
import { IPredefinedCustomDescription } from './predefinedCustomDescription.interface';
import { validateFiltersForQuery } from '../../../middlewares/queryValidation/paginationQueryValidationMiddleware';
